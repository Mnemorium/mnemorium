"""Generate `docs/development/artifacts/RequirementsTraceabilityCoverage.md`, the requirement and scenario matrix of
the specification
tree.

Run through `script/investigation.sh`; the module is standard-library only and imports no test module, so a conftest
fixture chain never runs to produce a document. It reads:

- `openspec/specs/*/spec.md`, for the declared requirements and scenarios;
- `test/system/*.py`, for each case's `@scenario("SCN-...", TestType...)` decorators and any `@positive`-style case
  decorator that types every scenario the case declares;
- `test/api/scenarios.toml`, for each scenario the fixture fuzz run proves and the kind of proof it carries;
- `src/**/*.rs`, for each `// proves: SCN-...` comment, the function below it and the kind the comment names after
  its em dash;
- the existing `docs/development/artifacts/RequirementsTraceabilityCoverage.md`, for the cells a human authored.

The derived columns are rewritten and the authored ones are preserved: a requirement's type cell survives unless it is
empty or a bare integer, and a scenario's `Cause` survives while it is non-empty. A row whose identifier left the
specification moves to `## Detached notes` instead of disappearing, and reappears from there when its identifier
returns. An `N/A` cell contradicted by a real proof is a warning and a `## Contradictions` line, never an overwrite.

A scenario row's `Evidence` names what proves it and no more: `System suite` for a `@scenario` claim, `API suite` for
an entry in `test/api/scenarios.toml`, `Proven in Rust` for a `// proves:` claim, and none for a scenario no committed
suite claims. Its `Type` is the kind the scenario names, the kind its case declares once, the kind the API manifest
gives it, or the kind its `// proves:` comment names after an em dash. The individual case and function names stay out
of the artefact; the annotation is the citation they already carry.

A requirement's status is presence-based: `Tested` means every scenario it declares carries a committed system claim or
an API-suite entry — not that a particular run passed. No timestamp, commit or run identifier is written, so a
regeneration with nothing changed produces no diff.
"""

from __future__ import annotations

import ast
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

REQUIREMENT_HEADER = re.compile(r"^### Requirement: (?P<identifier>REQ-[A-Z0-9-]+) — (?P<title>.+)$")
SCENARIO_HEADER = re.compile(r"^#### Scenario: (?P<identifier>SCN-[A-Z0-9-]+) — (?P<title>.+)$")
SCENARIO_IDENTIFIER = re.compile(r"^SCN-[A-Z0-9-]+-\d{3}-[A-Z]$")
CAPABILITY_OF = re.compile(r"^(?:REQ|SCN)-(?P<capability>.+?)-\d{3}(?:-[A-Z])?$")
RUST_PROVES = re.compile(r"^\s*// proves:\s*(?P<body>.+)$")
RUST_FUNCTION = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(?P<name>[A-Za-z0-9_]+)")
BARE_INTEGER = re.compile(r"^\d+$")

# The eight types, in the order the requirement matrix declares them (D14).
TYPE_LABELS = {
    "POSITIVE": "Positive",
    "NEGATIVE": "Negative",
    "BOUNDARY": "Boundary",
    "SECURITY": "Security",
    "ERROR_HANDLING": "Error handling",
    "RECOVERY": "Recovery",
    "ALTERNATE_FLOW": "Alternate flow",
    "BUSINESS_RULE": "Business rule",
}
TYPES = tuple(TYPE_LABELS.values())
# A case may declare its kind once for every scenario it proves: the bare decorator's name is the kind (`labels.py`).
CASE_TYPE_DECORATORS = {label.lower().replace(" ", "_"): label for label in TYPES}
# A `// proves:` comment may name its kind after an em dash, either as the label or as the decorator's bare name.
RUST_KINDS = {label: label for label in TYPES} | CASE_TYPE_DECORATORS

ARTEFACT = Path("docs/development/artifacts/RequirementsTraceabilityCoverage.md")
# The scenarios the fixture fuzz run proves. Nothing in that run is a pytest case, so the claims live in this file.
API_MANIFEST = Path("test/api/scenarios.toml")

SUMMARY_HEADERS = (
    "Capability",
    "Requirements",
    "Scenarios",
    "Tested",
    "Not tested",
    "Rust proofs",
    "Unspecified",
)
REQUIREMENT_HEADERS = (
    "Requirement",
    "Title",
    *TYPES,
    "Unspecified",
    "Tested",
    "Untested",
    "Status",
)
SCENARIO_HEADERS = ("Scenario", "Title", "Type", "Cause", "Evidence")
DETACHED_HEADERS = ("Identifier", "Kind", "Column", "Content")

# What a scenario row's `Evidence` cell names. The case and function names stay out of the artefact: the annotation in
# the suite is their citation, and a renamed test would only churn this table.
SYSTEM_SUITE = "System suite"
API_SUITE = "API suite"
RUST_PROOF = "Proven in Rust"
# An earlier generation filled an unproven `Cause` with this prefix. It is derived text, so it is not preserved as
# authored.
RUST_CAUSE_PREFIX = RUST_PROOF + ": "

INTRO = (
    "Generated by `script/investigation.sh` from `openspec/specs/**/spec.md` and the suites' own annotations.\n"
    "A requirement's `Status` is presence-based: `Tested` means every declared scenario carries a committed system\n"
    "case or an API-suite entry and CI is green. `Evidence` names what proves a scenario — `System suite`, `API\n"
    "suite`, `Proven in Rust`, or a combination — so an empty cell is a scenario no committed suite claims. A `Type`\n"
    "is the kind the scenario names, the kind its case declares once, the kind `test/api/scenarios.toml` gives it, or\n"
    "the kind its `// proves:` comment names after an em dash; `Cause` and `N/A` cells are authored by hand and are\n"
    "never overwritten."
)

DETACHED_INTRO = (
    "Rows whose identifier no longer appears in the specification. Their authored cells are kept here, one row per\n"
    "cell, and are restored when the identifier returns."
)


@dataclass
class Scenario:
    """One declared scenario, with the requirement and capability its identifier names."""

    identifier: str
    title: str
    requirement: str
    capability: str


@dataclass
class Requirement:
    """One declared requirement and the scenarios beneath it."""

    identifier: str
    title: str
    capability: str
    scenarios: list[Scenario] = field(default_factory=list)


@dataclass
class Claim:
    """A system case's declaration that it proves a scenario."""

    scenario: str
    kind: str | None
    test: str


@dataclass
class RustClaim:
    """A Rust function's declaration that it proves a scenario."""

    scenario: str
    location: str
    kind: str | None = None


def capability_of(identifier: str) -> str:
    """The capability an identifier names, as the specification directory spells it in upper case."""
    match = CAPABILITY_OF.match(identifier)
    if match is None:
        raise ValueError(f"{identifier!r} is not a requirement or scenario identifier")
    return match.group("capability")


def display_name(capability: str) -> str:
    """The heading a capability's section carries."""
    if capability == "API":
        return "API"
    return capability.replace("-", " ").title()


def numeric_suffix(identifier: str) -> int:
    """The number of a requirement identifier, for ordering."""
    return int(identifier.rsplit("-", 1)[1])


def requirement_of_scenario(identifier: str) -> str:
    """The requirement a scenario identifier belongs to."""
    return identifier.replace("SCN-", "REQ-", 1).rsplit("-", 1)[0]


def scenario_suffix(identifier: str) -> str:
    """The letter of a scenario identifier, for ordering."""
    return identifier.rsplit("-", 1)[1]


def parse_specifications(root: Path) -> tuple[dict[str, Requirement], dict[str, Scenario], list[str]]:
    """Read every capability specification into requirements and scenarios indexed by identifier."""
    requirements: dict[str, Requirement] = {}
    scenarios: dict[str, Scenario] = {}
    problems: list[str] = []

    for path in sorted((root / "openspec" / "specs").glob("*/spec.md")):
        current: Requirement | None = None
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            requirement_header = REQUIREMENT_HEADER.match(line)
            if requirement_header is not None:
                identifier = requirement_header.group("identifier")
                if identifier in requirements:
                    problems.append(f"{path}:{number}: duplicate requirement {identifier}")
                current = Requirement(identifier, requirement_header.group("title"), capability_of(identifier))
                requirements[identifier] = current
                continue

            scenario_header = SCENARIO_HEADER.match(line)
            if scenario_header is None:
                continue
            identifier = scenario_header.group("identifier")
            if identifier in scenarios:
                problems.append(f"{path}:{number}: duplicate scenario {identifier}")
                continue
            if not SCENARIO_IDENTIFIER.fullmatch(identifier):
                problems.append(f"{path}:{number}: {identifier} is not a well-formed scenario identifier")
                continue
            owner = requirement_of_scenario(identifier)
            if current is None or current.identifier != owner:
                declared = current.identifier if current is not None else "no requirement"
                problems.append(f"{path}:{number}: {identifier} is declared under {declared}, not {owner}")
                continue
            scenario = Scenario(identifier, scenario_header.group("title"), owner, capability_of(owner))
            scenarios[identifier] = scenario
            requirements[owner].scenarios.append(scenario)

    return requirements, scenarios, problems


def parse_system_claims(root: Path) -> tuple[list[Claim], list[str]]:
    """Read every system case's scenario decorators from the suite's AST."""
    claims: list[Claim] = []
    problems: list[str] = []

    for path in sorted((root / "test" / "system").glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) or not node.name.startswith("test_"):
                continue
            case_type, type_problem = _read_case_type(node)
            if type_problem is not None:
                problems.append(f"{path}:{node.lineno}: {node.name}: {type_problem}")
            declared: list[tuple[str, str | None]] = []
            for decorator in node.decorator_list:
                if not _is_scenario_decorator(decorator):
                    continue
                identifier, kind, problem = _read_scenario_call(decorator)
                if problem is not None:
                    problems.append(f"{path}:{decorator.lineno}: {node.name}: {problem}")
                    continue
                assert identifier is not None
                declared.append((identifier, kind))
            if case_type is not None and not declared:
                problems.append(f"{path}:{node.lineno}: {node.name}: declares a case-level type but no scenario")
            elif case_type is not None and all(own is not None and own != case_type for _, own in declared):
                problems.append(
                    f"{path}:{node.lineno}: {node.name}: declares {case_type}, which every scenario overrides"
                )
            for identifier, kind in declared:
                claims.append(Claim(identifier, kind or case_type, f"{path.name}::{node.name}"))

    return claims, problems


def _case_type_of(decorator: ast.expr) -> str | None:
    """The kind a bare case-level decorator names, or `None` when the decorator is not one."""
    if isinstance(decorator, ast.Name):
        return CASE_TYPE_DECORATORS.get(decorator.id)
    if isinstance(decorator, ast.Attribute):
        return CASE_TYPE_DECORATORS.get(decorator.attr)
    return None


def _read_case_type(node: ast.FunctionDef | ast.AsyncFunctionDef) -> tuple[str | None, str | None]:
    """The one kind a case declares for every scenario it proves, and a problem when it declares two."""
    labels = [label for decorator in node.decorator_list if (label := _case_type_of(decorator)) is not None]
    if len(set(labels)) > 1:
        return None, f"declares more than one case-level type: {', '.join(sorted(set(labels)))}"
    return (labels[0] if labels else None), None


def _is_scenario_decorator(decorator: ast.expr) -> bool:
    """Whether a decorator is the `scenario` entry point, bare or qualified."""
    if not isinstance(decorator, ast.Call):
        return False
    function = decorator.func
    return (isinstance(function, ast.Name) and function.id == "scenario") or (
        isinstance(function, ast.Attribute) and function.attr == "scenario"
    )


def _read_scenario_call(decorator: ast.Call) -> tuple[str | None, str | None, str | None]:
    """Read one `@scenario` call into its identifier, type label and a problem when malformed."""
    if not decorator.args:
        return None, None, "scenario decorator carries no string identifier"
    if not isinstance(decorator.args[0], ast.Constant) or not isinstance(decorator.args[0].value, str):
        return None, None, "scenario decorator carries no string identifier"
    identifier = decorator.args[0].value
    if not SCENARIO_IDENTIFIER.fullmatch(identifier):
        return None, None, f"{identifier!r} is not a well-formed scenario identifier"
    if decorator.keywords:
        return None, None, "scenario decorator takes the identifier and the type positionally"
    if len(decorator.args) > 2:
        return None, None, "scenario decorator takes one identifier and one optional type"
    if len(decorator.args) == 1:
        return identifier, None, None
    kind = decorator.args[1]
    if not isinstance(kind, ast.Attribute) or kind.attr not in TYPE_LABELS:
        return None, None, "scenario type is not a member of the closed TestType set"
    return identifier, TYPE_LABELS[kind.attr], None


def parse_api_claims(root: Path) -> tuple[dict[str, str], list[str]]:
    """Read the scenarios the fixture fuzz run proves, with the kind of proof each carries."""
    path = root / API_MANIFEST
    if not path.exists():
        return {}, []

    try:
        document = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as error:
        return {}, [f"{path}: {error}"]

    claims: dict[str, str] = {}
    problems: list[str] = []
    scenarios = document.get("scenarios", {})
    if not isinstance(scenarios, dict):
        return {}, [f"{path}: `scenarios` is not a table"]
    for identifier, kind in scenarios.items():
        if not SCENARIO_IDENTIFIER.fullmatch(identifier):
            problems.append(f"{path}: {identifier!r} is not a well-formed scenario identifier")
            continue
        if kind not in TYPES:
            problems.append(f"{path}: {identifier}: {kind!r} is not one of: {', '.join(TYPES)}")
            continue
        claims[identifier] = kind
    return claims, problems


def parse_rust_claims(root: Path) -> tuple[list[RustClaim], list[str]]:
    """Read every `// proves:` comment in the Rust tree and the function it introduces."""
    claims: list[RustClaim] = []
    problems: list[str] = []

    for path in sorted((root / "src").rglob("*.rs")):
        lines = path.read_text(encoding="utf-8").splitlines()
        for index, line in enumerate(lines):
            proves = RUST_PROVES.match(line)
            if proves is None:
                continue
            body = proves.group("body").strip()
            identifiers, _, note = body.partition(" — ")
            kind, kind_problem = _read_rust_kind(note)
            if kind_problem is not None:
                problems.append(f"{path}:{index + 1}: {kind_problem}")
                continue
            cited = [identifier.strip() for identifier in identifiers.split(",") if identifier.strip()]
            if not cited:
                problems.append(f"{path}:{index + 1}: `// proves:` cites no scenario")
                continue
            function = _next_function(lines, index + 1)
            if function is None:
                problems.append(f"{path}:{index + 1}: `// proves:` is not followed by a function")
                continue
            location = f"{path.relative_to(root).as_posix()}::{function}"
            for identifier in cited:
                if not SCENARIO_IDENTIFIER.fullmatch(identifier):
                    problems.append(f"{path}:{index + 1}: {identifier!r} is not a well-formed scenario identifier")
                    continue
                claims.append(RustClaim(identifier, location, kind))

    return claims, problems


def _read_rust_kind(note: str) -> tuple[str | None, str | None]:
    """The kind a `// proves:` comment declares after its em dash, and a problem when it names no type."""
    note = note.strip()
    if not note:
        return None, None
    label = RUST_KINDS.get(note)
    if label is None:
        return None, f"`// proves:` declares {note!r}, not one of: {', '.join(TYPES)}"
    return label, None


def _next_function(lines: list[str], start: int) -> str | None:
    """The name of the first function declared at or after a line."""
    for line in lines[start:]:
        function = RUST_FUNCTION.match(line)
        if function is not None:
            return function.group("name")
    return None


@dataclass
class Preserved:
    """The authored cells the previous artefact carries."""

    type_cells: dict[tuple[str, str], str] = field(default_factory=dict)
    causes: dict[str, str] = field(default_factory=dict)
    detached: dict[tuple[str, str, str], str] = field(default_factory=dict)


def parse_artefact(path: Path) -> Preserved:
    """Read the authored cells out of the existing artefact; an absent file carries none."""
    preserved = Preserved()
    if not path.exists():
        return preserved

    for table in _parse_tables(path.read_text(encoding="utf-8"), path):
        headers = table[0]
        if headers[:1] == ["Requirement"]:
            positions = {label: headers.index(label) for label in TYPES if label in headers}
            for row in table[1:]:
                identifier = row[0]
                for label, position in positions.items():
                    content = row[position]
                    if content and not BARE_INTEGER.fullmatch(content):
                        preserved.type_cells[(identifier, label)] = content
        elif headers[:1] == ["Scenario"]:
            if "Cause" not in headers:
                continue
            cause = headers.index("Cause")
            for row in table[1:]:
                content = row[cause]
                if content and not content.startswith(RUST_CAUSE_PREFIX):
                    preserved.causes[row[0]] = content
        elif headers == list(DETACHED_HEADERS):
            for row in table[1:]:
                preserved.detached[(row[0], row[1], row[2])] = row[3]

    return preserved


def _parse_tables(text: str, path: Path) -> list[list[list[str]]]:
    """Split every Markdown table in a document into header and data rows."""
    tables: list[list[list[str]]] = []
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.lstrip().startswith("|"):
            index += 1
            continue
        if index + 1 >= len(lines) or not _is_separator(lines[index + 1]):
            raise ValueError(f"{path}:{index + 1}: a table header is not followed by a separator row")
        headers = _split_row(line)
        rows: list[list[str]] = []
        index += 2
        while index < len(lines) and lines[index].lstrip().startswith("|"):
            row = _split_row(lines[index])
            if len(row) != len(headers):
                raise ValueError(f"{path}:{index + 1}: a table row has {len(row)} cells, the header has {len(headers)}")
            rows.append(row)
            index += 1
        tables.append([headers, *rows])
    return tables


def _is_separator(line: str) -> bool:
    """Whether a line is a Markdown table's alignment row."""
    cells = _split_row(line)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells)


def _split_row(line: str) -> list[str]:
    """Split a table row on its unescaped pipes and trim the padding."""
    cells: list[str] = []
    current: list[str] = []
    escaped = False
    for character in line.strip():
        if escaped:
            if character != "|":
                current.append("\\")
            current.append(character)
            escaped = False
        elif character == "\\":
            current.append(character)
            escaped = True
        elif character == "|":
            cells.append("".join(current).strip())
            current = []
        else:
            current.append(character)
    cells.append("".join(current).strip())
    # The row starts and ends with a pipe, so the first and last pieces are empty.
    return cells[1:-1]


def _cell(content: str) -> str:
    """Escape a value for a table cell."""
    return content.replace("|", r"\|")


def render_table(headers: list[str] | tuple[str, ...], rows: list[list[str]]) -> list[str]:
    """Render one Markdown table, padded the way Prettier pads it."""
    escaped_headers = [_cell(header) for header in headers]
    escaped_rows = [[_cell(cell) for cell in row] for row in rows]
    widths = [
        max(3, len(escaped_headers[column]), *(len(row[column]) for row in escaped_rows))
        for column in range(len(escaped_headers))
    ]
    rendered = ["| " + " | ".join(header.ljust(widths[index]) for index, header in enumerate(escaped_headers)) + " |"]
    rendered.append("| " + " | ".join("-" * width for width in widths) + " |")
    for row in escaped_rows:
        rendered.append("| " + " | ".join(cell.ljust(widths[index]) for index, cell in enumerate(row)) + " |")
    return rendered


@dataclass
class Matrix:
    """The derived state of one generation."""

    requirements: dict[str, Requirement]
    scenarios: dict[str, Scenario]
    claims: list[Claim]
    api_claims: dict[str, str]
    rust_claims: list[RustClaim]
    capabilities: list[str]
    preserved: Preserved


def build_capabilities(root: Path) -> list[str]:
    """Every capability the specification tree declares, alphabetically."""
    return sorted(path.parent.name.upper() for path in (root / "openspec" / "specs").glob("*/spec.md"))


def render(matrix: Matrix) -> tuple[str, list[str], int]:
    """Render the artefact, returning its text, the contradictions and the unproven-Cause count."""
    requirements = matrix.requirements
    scenarios = matrix.scenarios
    claims = matrix.claims
    api_claims = matrix.api_claims
    rust_claims = matrix.rust_claims
    preserved = matrix.preserved

    claims_by_scenario: dict[str, list[Claim]] = {}
    for claim in claims:
        claims_by_scenario.setdefault(claim.scenario, []).append(claim)
    rust_proven = {claim.scenario for claim in rust_claims}
    rust_kinds: dict[str, set[str]] = {}
    for claim in rust_claims:
        if claim.kind is not None:
            rust_kinds.setdefault(claim.scenario, set()).add(claim.kind)

    type_overrides = dict(preserved.type_cells)
    causes = dict(preserved.causes)
    detached = dict(preserved.detached)

    # Restore a cell whose identifier is back only while it is still empty.
    for (identifier, kind, column), content in list(detached.items()):
        if identifier in requirements and kind == "requirement" and column in TYPES:
            if (identifier, column) not in type_overrides:
                type_overrides[(identifier, column)] = content
            del detached[(identifier, kind, column)]
        elif identifier in scenarios and kind == "scenario" and column == "Cause":
            if identifier not in causes:
                causes[identifier] = content
            del detached[(identifier, kind, column)]

    contradictions: list[str] = []
    unproven = 0

    summary_rows: list[list[str]] = []
    sections: list[list[str]] = []
    totals = [0, 0, 0, 0, 0, 0]

    for capability in matrix.capabilities:
        declared = sorted(
            (requirement for requirement in requirements.values() if requirement.capability == capability),
            key=lambda requirement: numeric_suffix(requirement.identifier),
        )
        requirement_rows: list[list[str]] = []
        scenario_rows: list[list[str]] = []

        capability_tested = 0
        capability_rust = 0
        capability_unspecified = 0

        for requirement in declared:
            tested: set[str] = set()
            counts = {label: set() for label in TYPES}
            unspecified: set[str] = set()
            for scenario in requirement.scenarios:
                scenario_claims = claims_by_scenario.get(scenario.identifier, [])
                api_kind = api_claims.get(scenario.identifier)
                if scenario_claims or api_kind is not None:
                    tested.add(scenario.identifier)
                kinds = {claim.kind for claim in scenario_claims if claim.kind is not None}
                kinds |= rust_kinds.get(scenario.identifier, set())
                if api_kind is not None:
                    kinds.add(api_kind)
                if scenario_claims and not kinds:
                    unspecified.add(scenario.identifier)
                for kind in kinds:
                    counts[kind].add(scenario.identifier)

            derived = {label: len(counts[label]) for label in TYPES}
            row = [requirement.identifier, requirement.title]
            for label in TYPES:
                authored = type_overrides.get((requirement.identifier, label))
                if authored is not None:
                    row.append(authored)
                    if derived[label] > 0:
                        proofs = f"{derived[label]} proof{' exists' if derived[label] == 1 else 's exist'}"
                        contradictions.append(f"`{requirement.identifier}`: {label} marked `{authored}` but {proofs}")
                else:
                    row.append(str(derived[label]))
            row.extend(
                [
                    str(len(unspecified)),
                    str(len(tested)),
                    str(len(requirement.scenarios) - len(tested)),
                    _status(len(tested), len(requirement.scenarios)),
                ]
            )
            requirement_rows.append(row)

            capability_tested += len(tested)
            capability_unspecified += len(unspecified)
            capability_rust += sum(
                1
                for scenario in requirement.scenarios
                if scenario.identifier in rust_proven and scenario.identifier not in tested
            )

            for scenario in sorted(requirement.scenarios, key=lambda item: scenario_suffix(item.identifier)):
                scenario_claims = claims_by_scenario.get(scenario.identifier, [])
                proved_in_rust = scenario.identifier in rust_proven
                api_kind = api_claims.get(scenario.identifier)
                kinds = {claim.kind for claim in scenario_claims if claim.kind is not None}
                kinds |= rust_kinds.get(scenario.identifier, set())
                if api_kind is not None:
                    kinds.add(api_kind)
                evidence = []
                if scenario_claims:
                    evidence.append(SYSTEM_SUITE)
                if api_kind is not None:
                    evidence.append(API_SUITE)
                if proved_in_rust:
                    evidence.append(RUST_PROOF)
                cause = causes.get(scenario.identifier, "")
                if not scenario_claims and api_kind is None and not cause and not proved_in_rust:
                    unproven += 1
                scenario_rows.append(
                    [
                        scenario.identifier,
                        scenario.title,
                        ", ".join(label for label in TYPES if label in kinds),
                        cause,
                        ", ".join(evidence),
                    ]
                )

        declared_count = sum(len(requirement.scenarios) for requirement in declared)
        not_tested = declared_count - capability_tested
        summary_rows.append(
            [
                capability.lower(),
                str(len(declared)),
                str(declared_count),
                str(capability_tested),
                str(not_tested),
                str(capability_rust),
                str(capability_unspecified),
            ]
        )
        totals = [
            totals[0] + len(declared),
            totals[1] + declared_count,
            totals[2] + capability_tested,
            totals[3] + not_tested,
            totals[4] + capability_rust,
            totals[5] + capability_unspecified,
        ]

        sections.extend(
            [
                ["---"],
                [""],
                [f"## {display_name(capability)}"],
                [""],
                ["### Requirements"],
                [""],
                render_table(REQUIREMENT_HEADERS, requirement_rows),
                [""],
                ["### Scenarios"],
                [""],
                render_table(SCENARIO_HEADERS, scenario_rows),
                [""],
            ]
        )

    summary_rows.append(["**total**", *(str(total) for total in totals)])

    # Rows that left the specification keep their authored cells.
    current_requirements = set(requirements)
    current_scenarios = set(scenarios)
    for identifier in {key[0] for key in type_overrides}:
        if identifier not in current_requirements:
            for label in TYPES:
                if (identifier, label) in type_overrides:
                    detached[(identifier, "requirement", label)] = type_overrides[(identifier, label)]
    for identifier, content in causes.items():
        if identifier not in current_scenarios:
            detached[(identifier, "scenario", "Cause")] = content

    lines: list[str] = ["# Requirements traceability coverage", "", INTRO, "", "## Summary", ""]
    lines.extend(render_table(SUMMARY_HEADERS, summary_rows))
    lines.append("")
    for section in sections:
        lines.extend(section)

    if detached:
        lines.extend(["---", "", "## Detached notes", "", DETACHED_INTRO, ""])
        rows = [[key[0], key[1], key[2], detached[key]] for key in sorted(detached)]
        lines.extend(render_table(DETACHED_HEADERS, rows))
        lines.append("")

    if contradictions:
        lines.extend(["---", "", "## Contradictions", ""])
        lines.extend(f"- {contradiction}." for contradiction in contradictions)
        lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n", contradictions, unproven


def _status(tested: int, declared: int) -> str:
    """A requirement's status from how many of its scenarios carry a claim."""
    if declared == 0 or tested == 0:
        return "Not tested"
    if tested == declared:
        return "Tested"
    return "Partial"


def main(root: Path) -> int:
    """Generate the artefact and return the process exit code."""
    try:
        requirements, scenarios, problems = parse_specifications(root)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 2

    claims, claim_problems = parse_system_claims(root)
    api_claims, api_problems = parse_api_claims(root)
    rust_claims, rust_problems = parse_rust_claims(root)
    problems = claim_problems + api_problems + rust_problems

    known = set(scenarios)
    for claim in claims:
        if claim.scenario not in known:
            problems.append(f"{claim.test}: claims {claim.scenario}, which no specification declares")
    for identifier in api_claims:
        if identifier not in known:
            problems.append(f"{API_MANIFEST}: {identifier} is not declared by any specification")
    for claim in rust_claims:
        if claim.scenario not in known:
            problems.append(f"{claim.location}: proves {claim.scenario}, which no specification declares")
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 2

    artefact = root / ARTEFACT
    try:
        preserved = parse_artefact(artefact)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    matrix = Matrix(
        requirements=requirements,
        scenarios=scenarios,
        claims=claims,
        api_claims=api_claims,
        rust_claims=rust_claims,
        capabilities=build_capabilities(root),
        preserved=preserved,
    )
    text, contradictions, unproven = render(matrix)
    artefact.parent.mkdir(parents=True, exist_ok=True)
    artefact.write_text(text, encoding="utf-8")

    for contradiction in contradictions:
        print(f"warning: {contradiction}", file=sys.stderr)
    if unproven:
        print(
            f"warning: {unproven} not-tested scenario{'s' if unproven != 1 else ''} carry no Cause and no Rust proof; "
            "they are the worklist",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    arguments = sys.argv[1:]
    if len(arguments) != 1:
        print("usage: python3 -m investigation <repository-root>", file=sys.stderr)
        raise SystemExit(2)
    raise SystemExit(main(Path(arguments[0])))

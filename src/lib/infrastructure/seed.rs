/// Directory holding one fixture's scripts and media, relative to the working
/// directory.
///
/// The tree is an input at boot, not part of the binary: a launcher mounts or
/// links it beside the working directory, so a fixture change is data rather
/// than a rebuild. Embedded scripts would rebuild the crate on every edit.
const API_FIXTURE: &str = "test/api/seed";
/// The volume library the performance suite extends the API fixture with.
const PERF_FIXTURE: &str = "test/performance/seed";
/// The browsable catalogue the system suite addresses.
const SYSTEM_FIXTURE: &str = "test/system/seed";

/// Prefix the API fixture's file paths share under the library root.
const API_FILE_PREFIX: &str = "seed/";
/// Prefix the system fixture's file paths share under the library root.
const SYSTEM_FILE_PREFIX: &str = "system/";

/// Size of the bulk image base, in bytes.
///
/// Shared with `script/generate_perf_seed.sh`, whose `file` rows carry this
/// value. A mismatch makes the startup scan re-probe every bulk file.
const PERF_IMAGE_BYTES: u64 = 1024;
/// Size of the bulk video base, in bytes.
const PERF_VIDEO_BYTES: u64 = 2048;
/// Size of the bulk audio base, in bytes.
const PERF_AUDIO_BYTES: u64 = 4096;
/// Size of the multi-megabyte stream base the read-asset flow measures.
const PERF_STREAM_BYTES: u64 = 4_194_304;
/// Modification instant every bulk file, and its base, shares.
///
/// Whole seconds on purpose: `modified_at` is stored as text without
/// sub-second precision, so equality must not depend on it.
const PERF_MODIFIED_AT_EPOCH_S: u64 = 1_577_836_800;

/// The bulk file bases, one per media kind plus the stream asset.
///
/// The hidden directory matters: the startup walk skips entries whose name
/// starts with a dot, so a base is never registered as a library file.
const PERF_BASES: [PerfBase; 4] = [
    PerfBase {
        name: "image.png",
        size_bytes: PERF_IMAGE_BYTES,
        seed: include_bytes!("../../../test/api/seed/media/cover.png"),
    },
    PerfBase {
        name: "video.mp4",
        size_bytes: PERF_VIDEO_BYTES,
        seed: include_bytes!("../../../test/api/seed/media/clip.mp4"),
    },
    PerfBase {
        name: "audio.flac",
        size_bytes: PERF_AUDIO_BYTES,
        seed: include_bytes!("../../../test/api/seed/media/track.flac"),
    },
    PerfBase {
        name: "stream.mp4",
        size_bytes: PERF_STREAM_BYTES,
        seed: include_bytes!("../../../test/api/seed/media/audiovisual.mp4"),
    },
];

/// A hardlink base the bulk files share.
struct PerfBase {
    /// File name under `perf/.base/`.
    name: &'static str,
    /// Seed bytes repeated to fill `size_bytes`.
    seed: &'static [u8],
    /// Exact byte length the generated rows declare.
    size_bytes: u64,
}

/// A demo account the seed creates.
struct SeedUser {
    /// Identifier of the `credential` row.
    credential_id: i64,
    /// Contact address; `None` when the account has no email.
    email: &'static str,
    /// Role the account holds.
    role: &'static str,
    /// Identifier of the `user` row.
    user_id: i64,
    /// Login name.
    username: &'static str,
}

/// Apply the `profile` fixture to `pool`.
///
/// The fixtures live beside the working directory rather than inside the
/// binary, so `library_root` receives the bytes their rows name and the scripts
/// are resolved at boot. The API fixture creates its accounts before its scripts
/// run, because the scripts refer to the identifiers they own; the volume
/// library is applied after the API fixture it extends, and the system fixture
/// owns its own tree. Applying the seed twice is a no-op: every insert tolerates
/// an existing row and each script set runs once through its own history table. A
/// boot that names no profile applies no fixture.
///
/// # Errors
///
/// Returns an error when a fixture tree is absent or unreadable, when a seeded
/// file cannot be materialised, when an identity cannot be hashed, or when the
/// scripts fail. The library root is created when absent: a normal build still
/// never creates the operator's mount, but a seeded run owns the directory it is
/// about to populate.
pub(crate) async fn apply(
    pool: &SqlitePool,
    pepper: &str,
    library_root: &Path,
    profile: Option<SeedProfile>,
) -> anyhow::Result<()> {
    let Some(selected) = profile else {
        return Ok(());
    };

    fs::create_dir_all(library_root).await?;

    match selected {
        SeedProfile::Api => seed_api(pool, pepper, library_root).await?,
        SeedProfile::Perf => {
            seed_api(pool, pepper, library_root).await?;
            seed_perf(pool, library_root).await?;
        }
        SeedProfile::System => seed_system(pool, pepper, library_root).await?,
    }

    info!(profile = ?selected, "test seed data applied");
    Ok(())
}

/// Apply the small demo library the API fixture and Schemathesis address.
async fn seed_api(pool: &SqlitePool, pepper: &str, library_root: &Path) -> anyhow::Result<()> {
    let accounts = seed_identities(pool, pepper, &SEED_USERS, SEED_PASSWORD).await?;
    apply_fixture(pool, API_FIXTURE, "_sqlx_seeds_api").await?;
    ground_files(pool, API_FIXTURE, library_root, API_FILE_PREFIX).await?;

    if accounts > 0 {
        show_demo_accounts();
    }
    Ok(())
}

/// Apply the volume library the performance suite measures over the API fixture.
async fn seed_perf(pool: &SqlitePool, library_root: &Path) -> anyhow::Result<()> {
    // The hardlink bases are written before the migrator so a row can only be
    // created once its bytes are available. Grounding the visible links waits
    // for the migrator: the rows are what name them.
    prepare_perf_bases(library_root).await?;

    apply_fixture(pool, PERF_FIXTURE, "_sqlx_seeds_perf").await?;

    // A row without its file is deleted by the startup scan, and a file without
    // its row is registered and probed. Both are paid for on every `test-seed`
    // boot, so the seed leaves neither state behind.
    seed_perf_links(pool, library_root).await?;
    Ok(())
}

/// Apply the browsable catalogue the system suite addresses.
async fn seed_system(pool: &SqlitePool, pepper: &str, library_root: &Path) -> anyhow::Result<()> {
    let accounts = seed_identities(pool, pepper, &SYSTEM_USERS, SYSTEM_SEED_PASSWORD).await?;
    apply_fixture(pool, SYSTEM_FIXTURE, "_sqlx_seeds_system").await?;
    ground_files(pool, SYSTEM_FIXTURE, library_root, SYSTEM_FILE_PREFIX).await?;

    if accounts > 0 {
        show_system_account();
    }
    Ok(())
}

/// Run one fixture's scripts through a migrator of its own.
///
/// The scripts are resolved from the fixture tree at boot rather than embedded,
/// so editing one is a data change instead of a rebuild. Each fixture keeps its
/// own history table, so the three sets never see each other's versions.
async fn apply_fixture(
    pool: &SqlitePool,
    fixture: &str,
    table_name: &'static str,
) -> anyhow::Result<()> {
    let directory = Path::new(fixture).join("sql");
    let mut migrator = Migrator::new(directory.as_path()).await.with_context(|| {
        format!(
            "the seed fixture {} is absent; mount or link the fixture tree beside the working directory",
            directory.display()
        )
    })?;
    migrator.dangerous_set_table_name(table_name);
    migrator.run(pool).await?;
    Ok(())
}

/// Create the given accounts and their credentials, returning how many users
/// were inserted.
async fn seed_identities(
    pool: &SqlitePool,
    pepper: &str,
    users: &[SeedUser],
    password: &str,
) -> anyhow::Result<u64> {
    let hasher = Argon2PasswordHasher::new(pepper.as_bytes().to_vec());
    let mut created = 0u64;

    for account in users {
        let password_hash = hasher.hash_password(password).await?;
        sqlx::query(
            "INSERT INTO credential (credential_id, password_hash)
             VALUES (?1, ?2)
             ON CONFLICT DO NOTHING",
        )
        .bind(account.credential_id)
        .bind(&password_hash)
        .execute(pool)
        .await?;

        let inserted = sqlx::query(
            "INSERT INTO user (user_id, role, username, email, credential_id)
             VALUES (?1, ?2, ?3, ?4, ?5)
             ON CONFLICT DO NOTHING",
        )
        .bind(account.user_id)
        .bind(account.role)
        .bind(account.username)
        .bind(account.email)
        .bind(account.credential_id)
        .execute(pool)
        .await?
        .rows_affected();

        created = created.saturating_add(inserted);

        // Every account is a resource under the instance root, and the Admin
        // role grant gives the seeded Admin owner-level reach over it
        // (`REQ-AUTHORIZATION-019`, `-035`).
        sqlx::query(
            "INSERT INTO resource (kind, entity_id, owner_id, auth_parent_id, visibility)
             VALUES ('USER', ?1, NULL, 1, 'PRIVATE')
             ON CONFLICT DO NOTHING",
        )
        .bind(account.user_id)
        .execute(pool)
        .await?;
        sqlx::query(
            "INSERT INTO grant (
                 principal_kind, principal_id, principal_role, resource_id,
                 role, child_kind, effect
             )
             SELECT 'ROLE', NULL, 'ADMIN', resource_id, 'OWNER', 'ALL', 'ALLOW'
             FROM resource WHERE kind = 'USER' AND entity_id = ?1
             ON CONFLICT DO NOTHING",
        )
        .bind(account.user_id)
        .execute(pool)
        .await?;
    }

    Ok(created)
}

/// Ground the fixture's file rows to the bytes under the library root.
///
/// The scripts declare each row, so this step owns the two values only the
/// filesystem can supply: the size and the modification instant the startup scan
/// compares. A launcher mounts the fixture's media at the row's own directory, so
/// the path resolves with nothing to copy; when no mount names it — a `cargo run`
/// from the repository root, or a host binary whose working directory is a
/// scratch tree — the committed file is copied in from the fixture's `media/`
/// directory instead.
///
/// The step runs on every boot although the scripts run once, so a deleted
/// library root or an interrupted first boot heals without a rebuild.
async fn ground_files(
    pool: &SqlitePool,
    fixture: &str,
    library_root: &Path,
    prefix: &str,
) -> anyhow::Result<()> {
    let pattern = format!("{prefix}%");
    let rows: Vec<(i64, String, i64, chrono::NaiveDateTime)> = sqlx::query_as(
        "SELECT file_id, path, size_bytes, modified_at FROM file
         WHERE path LIKE ?1
         ORDER BY file_id",
    )
    .bind(&pattern)
    .fetch_all(pool)
    .await?;

    let media = Path::new(fixture).join("media");

    for (file_id, path, recorded_size, recorded_at) in rows {
        let absolute = library_root.join(&path);

        if !absolute.exists() {
            let name = Path::new(&path)
                .file_name()
                .with_context(|| format!("the seeded file {path} names no file to copy"))?;
            let source = media.join(name);
            if let Some(directory) = absolute.parent() {
                fs::create_dir_all(directory).await?;
            }
            fs::copy(&source, &absolute).await.with_context(|| {
                format!(
                    "the seed fixture file {} is absent; mount or link the fixture tree beside the working directory",
                    source.display()
                )
            })?;
        }

        // The scan compares the record against the file's size and modification
        // instant, so both are read after the bytes are in place.
        let metadata = fs::metadata(&absolute)
            .await
            .with_context(|| format!("the seeded file {path} is absent from the library root"))?;
        let size_bytes = i64::try_from(metadata.len())?;
        let modified_at = DateTime::<Utc>::from(metadata.modified()?).naive_utc();
        if recorded_size == size_bytes && recorded_at == modified_at {
            continue;
        }

        sqlx::query("UPDATE file SET size_bytes = ?1, modified_at = ?2 WHERE file_id = ?3")
            .bind(size_bytes)
            .bind(modified_at)
            .bind(file_id)
            .execute(pool)
            .await?;
    }

    Ok(())
}

/// Write the hardlink bases the bulk file rows point at.
///
/// Each base is filled to its declared size and stamped with the shared
/// modification instant. The base directory is hidden, so the startup walk
/// skips it and only the visible links are reconciled.
async fn prepare_perf_bases(library_root: &Path) -> anyhow::Result<()> {
    let directory: PathBuf = library_root.join("perf/.base");
    fs::create_dir_all(&directory).await?;
    let modified = UNIX_EPOCH
        .checked_add(Duration::from_secs(PERF_MODIFIED_AT_EPOCH_S))
        .context("the perf base instant is representable")?;

    for base in &PERF_BASES {
        let path = directory.join(base.name);
        let length = usize::try_from(base.size_bytes)?;
        let needs_write =
            blocking_fs::metadata(&path).map_or(true, |metadata| metadata.len() != base.size_bytes);
        if needs_write {
            let mut bytes = Vec::with_capacity(length);
            while bytes.len() < length {
                let remaining = length.saturating_sub(bytes.len());
                let take = remaining.min(base.seed.len());
                let piece = base
                    .seed
                    .get(..take)
                    .context("the base seed slice is in range")?;
                bytes.extend_from_slice(piece);
            }
            fs::write(&path, &bytes).await?;
        }

        // The write resets the instant to "now", so stamp it afterwards on
        // every run, not only when the bytes changed.
        let stamped = path.clone();
        spawn_blocking(move || -> io::Result<()> {
            let file = blocking_fs::File::options().write(true).open(&stamped)?;
            file.set_times(blocking_fs::FileTimes::new().set_modified(modified))
        })
        .await
        .map_err(|error| anyhow::anyhow!("the base stamp task failed: {error}"))??;
    }

    Ok(())
}

/// Hardlink every bulk `file` row to its base, idempotently.
///
/// The rows are the authority on which paths exist: the generator derives
/// them arithmetically, and this step only grounds the paths they name. An
/// existing link whose size or instant drifted from the base is relinked,
/// because the scan compares exactly those two values.
async fn seed_perf_links(pool: &SqlitePool, library_root: &Path) -> anyhow::Result<()> {
    let rows: Vec<(String, String, i64)> =
        sqlx::query_as("SELECT path, mime_type_id, size_bytes FROM file WHERE path LIKE 'perf/%'")
            .fetch_all(pool)
            .await?;
    if rows.is_empty() {
        return Ok(());
    }

    let root = library_root.to_path_buf();
    let modified = UNIX_EPOCH
        .checked_add(Duration::from_secs(PERF_MODIFIED_AT_EPOCH_S))
        .context("the perf base instant is representable")?;
    spawn_blocking(move || -> anyhow::Result<()> {
        let base_directory = root.join("perf/.base");
        for row in &rows {
            let relative = &row.0;
            let expected = u64::try_from(row.2)?;
            let base = match (row.1.as_str(), expected) {
                ("image/png", _) => "image.png",
                ("audio/flac", _) => "audio.flac",
                ("video/mp4", PERF_STREAM_BYTES) => "stream.mp4",
                ("video/mp4", _) => "video.mp4",
                _ => continue,
            };
            let link = root.join(relative);
            let matches = blocking_fs::metadata(&link).is_ok_and(|metadata| {
                metadata.len() == expected
                    && metadata.modified().is_ok_and(|instant| instant == modified)
            });
            if matches {
                continue;
            }
            if let Some(parent) = link.parent() {
                blocking_fs::create_dir_all(parent)?;
            }
            match blocking_fs::remove_file(&link) {
                Ok(()) => {}
                Err(error) if error.kind() == io::ErrorKind::NotFound => {}
                Err(error) => return Err(error.into()),
            }
            blocking_fs::hard_link(base_directory.join(base), &link)?;
            let grounded = blocking_fs::metadata(&link).is_ok_and(|metadata| {
                metadata.len() == expected
                    && metadata.modified().is_ok_and(|instant| instant == modified)
            });
            if !grounded {
                anyhow::bail!(
                    "the seeded file {} does not match its base after a hardlink",
                    link.display()
                );
            }
        }
        Ok(())
    })
    .await
    .map_err(|error| anyhow::anyhow!("the perf link task failed: {error}"))??;

    Ok(())
}


#![cfg(feature = "test-seed")]

//! Test-only seed data, compiled only with the `test-seed` feature.
//!
//! Three fixtures live side by side and a boot applies the one its profile
//! names; a boot that names no profile applies none:
//!
//! - `test/api/seed` is the demo library Schemathesis addresses. It stays small
//!   on purpose: every list response is a handful of rows, so fuzzing it costs
//!   minutes.
//! - `test/performance/seed` is the volume library the black-box performance
//!   suite measures, selected with `MNEMORIUM_SEED_PROFILE=perf`. It is applied
//!   after the API fixture and adds 19 048 media and file rows, 100 playlists
//!   and 3 000 containers, which is why it is never the default: the same fuzz
//!   run against it takes ten times longer.
//! - `test/system/seed` is the browsable catalogue the system suite addresses,
//!   selected with `MNEMORIUM_SEED_PROFILE=system`. One identity, `coverart`,
//!   owns the gallery and playlist the modules read, and every library row is
//!   `PUBLIC` so a case can follow a link it did not create.
//!
//! The fixtures are read from the working directory at boot, not embedded: a
//! launcher mounts or links the tree beside the working directory, so adding a
//! row or a media file is a data change instead of a rebuild. Each fixture's
//! scripts are applied once through a `sqlx` migrator with its own history table
//! (`_sqlx_seeds_api`, `_sqlx_seeds_perf`, `_sqlx_seeds_system`). The demo
//! identities are created here because SQL cannot reproduce an Argon2 hash bound
//! to the live instance pepper; the `file` rows are declared by the scripts, and
//! this module grounds them to the bytes a launcher supplies, recording the size
//! and modification instant a scan compares.
//!
//! The fixed identifiers are shared with the SQL scripts, which name them in
//! their header comment: the API fixture owns `9001`-`9007` and the accounts
//! `9001`-`9002`; the system fixture owns `10000`-`19999`, one 1000-wide block
//! per module, and the identity `coverart` is `10000`.
//!
//! The volume library is generated by `script/generate_perf_seed.sh`. Its
//! `file` rows name paths under `perf/`; this module writes one hidden hardlink
//! base per media type under `perf/.base/` and grounds every row's path to it,
//! so the startup scan reports each file `Untouched`.

